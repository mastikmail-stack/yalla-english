self.addEventListener('message', e => {
  if (e.data?.type === 'ACTIVATE_UPDATE') self.skipWaiting();
});

self.addEventListener('install', (e) => {
  // Bypass the browser's HTTP cache, which can still hold the previous release
  // after GitHub Pages publishes. A new cache name alone does not do this.
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map(path =>
    new Request(new URL(path, self.registration.scope), {cache:'reload'})
  ))));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('yalla-english-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== self.location.origin) return;
  const known = FILES.some(path => new URL(path, self.registration.scope).pathname === url.pathname);
  if (!known && e.request.mode !== 'navigate') return;
  e.respondWith(
    caches.open(CACHE).then(async cache => {
      const cached = await cache.match(e.request, {ignoreSearch:true});
      if (cached) return cached;
      try { return await fetch(e.request); }
      catch (error) {
        if (e.request.mode === 'navigate') return (await cache.match('./index.html')) || Response.error();
        return Response.error();
      }
    })
  );
});
