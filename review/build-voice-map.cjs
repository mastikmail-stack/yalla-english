/*
 * Build js/voice-audio.js (runtime map text -> file per voice) from the voice manifests,
 * and refresh the audio entries in sw.js so every voice recording is cached for offline use.
 * Run automatically by generate-elevenlabs.cjs; safe to run by hand: node review/build-voice-map.cjs
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const voices = JSON.parse(fs.readFileSync(path.join(__dirname, 'voices.config.json'), 'utf8'));
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'audio/production/utterances.json'), 'utf8')).items;

// Same key rule as js/audio.js: single capital letter stays as is, everything else is normalized.
const keyOf = text => /^[A-Z]$/.test(text) ? text : String(text).trim().toLowerCase().replace(/[.!?,]+$/g, '');

const runtime = { default: voices[0].key, voices: [], files: {} };
const audioFiles = [];
for (const voice of voices) {
  let manifest = null;
  try { manifest = JSON.parse(fs.readFileSync(path.join(root, 'audio/voices', voice.key, 'manifest.json'), 'utf8')); } catch { /* not produced yet */ }
  const files = {};
  let count = 0;
  for (const item of catalog) {
    const entry = manifest?.items?.[item.id];
    if (!entry) continue;
    const abs = path.join(root, entry.file);
    if (!fs.existsSync(abs)) continue;
    if (crypto.createHash('sha256').update(fs.readFileSync(abs)).digest('hex') !== entry.sha256) throw new Error(`hash mismatch ${entry.file}`);
    const k = keyOf(item.expectedSpokenText);
    if (!files[k]) files[k] = entry.file; // letter I and pronoun I, "Good morning" word/sentence share one spoken form
    if (!audioFiles.includes(entry.file)) audioFiles.push(entry.file);
    count++;
  }
  runtime.voices.push({ key: voice.key, label: voice.label, gender: voice.gender, count, total: catalog.length, complete: count === catalog.length });
  runtime.files[voice.key] = files;
}

const js = `/* Generated by review/build-voice-map.cjs from audio/voices/<voice>/manifest.json. Do not edit by hand. */
window.YALLA_VOICES = ${JSON.stringify(runtime, null, 1)};
(function deepFreeze(o) { Object.freeze(o); Object.values(o).forEach(v => { if (v && typeof v === 'object' && !Object.isFrozen(v)) deepFreeze(v); }); })(window.YALLA_VOICES);
`;
fs.writeFileSync(path.join(root, 'js/voice-audio.js'), js);

// Rewrite the audio block of the service worker file list (between the VOICE AUDIO markers).
const swPath = path.join(root, 'sw.js');
let sw = fs.readFileSync(swPath, 'utf8');
const block = /  \/\/ BEGIN VOICE AUDIO\n[\s\S]*?  \/\/ END VOICE AUDIO/;
if (!block.test(sw)) throw new Error('VOICE AUDIO markers not found in sw.js');
const listed = audioFiles.sort().map(f => `  "./${f}",`);
sw = sw.replace(block, ['  // BEGIN VOICE AUDIO', ...listed, '  // END VOICE AUDIO'].join('\n'));
fs.writeFileSync(swPath, sw);
console.log(runtime.voices.map(v => `${v.key}: ${v.count}/${v.total}${v.complete ? ' complete' : ''}`).join(' | '), `| sw audio files: ${audioFiles.length}`);
